const mongoose = require("mongoose");

// ======================================================
// TIFFIN PLAN SCHEMA
// ======================================================

const tiffinPlanSchema = new mongoose.Schema(

    {

        // ==================================================
        // TIFFIN SELLER
        // ==================================================

        seller: {

            type: mongoose.Schema.Types.ObjectId,

            ref: "TiffinSeller",

            required: true

        },


        // ==================================================
        // PLAN NAME
        // ==================================================

        name: {

            type: String,

            required: true,

            trim: true

        },


        // ==================================================
        // PLAN TYPE
        // ==================================================

        type: {

            type: String,

            enum: [
                "weekly",
                "one_day",
                "monthly",
                "yearly",
                "half_yearly"
            ],

            required: true

        },


        // ==================================================
        // PRICE
        // ==================================================

        price: {

            type: Number,

            required: true,

            min: 0

        },


        // ==================================================
        // DESCRIPTION
        // ==================================================

        description: {

            type: String,

            default: "",

            trim: true

        },


        // ==================================================
        // MEALS
        // ==================================================

        meals: {

            type: Number,

            default: 1,

            min: 1

        },


        // ==================================================
        // PLAN STATUS
        // ==================================================

        status: {

            type: String,

            enum: [
                "active",
                "deactive"
            ],

            default: "active"

        },


        // ==================================================
        // PLAN IMAGE
        // ==================================================

        image: {

            type: String,

            default: ""

        },


        // ==================================================
        // TOTAL ORDERS
        // ==================================================

        totalOrders: {

            type: Number,

            default: 0

        },


        // ==================================================
        // TOTAL DELIVERED
        // ==================================================

        totalDelivered: {

            type: Number,

            default: 0

        }

    },

    {

        timestamps: true

    }

);


// ======================================================
// MODEL
// ======================================================

const TiffinPlan =
    mongoose.model(
        "TiffinPlan",
        tiffinPlanSchema
    );


// ======================================================
// EXPORT
// ======================================================

module.exports = TiffinPlan;